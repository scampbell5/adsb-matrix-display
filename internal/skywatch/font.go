func drawText5x7(setPixel func(int, int, color.Color), x, y int, text string, c color.Color) int {
	cx := x
	for _, r := range text {
		glyph, ok := font5x7[r]
		if !ok {
			glyph = font5x7[' ']
		}
		for yy, row := range glyph {
			for xx := 0; xx < 5; xx++ {
				if row&(1<<(4-xx)) != 0 {
					setPixel(cx+xx, y+yy, c)
				}
			}
		}
		cx += 6
	}
	return cx
}

